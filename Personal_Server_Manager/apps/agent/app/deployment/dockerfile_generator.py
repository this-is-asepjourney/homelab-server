def detect_project_stack(workspace_dir: str) -> Dict[str, Any]:
    """
    Intelligently inspects a directory or repo to determine the technology stack,
    framework, package manager, and optimal container configuration.
    """
    composer_json = os.path.join(workspace_dir, "composer.json")
    artisan_file = os.path.join(workspace_dir, "artisan")
    pkg_json_file = os.path.join(workspace_dir, "package.json")
    req_txt = os.path.join(workspace_dir, "requirements.txt")
    pyproject_toml = os.path.join(workspace_dir, "pyproject.toml")
    pipfile = os.path.join(workspace_dir, "Pipfile")
    go_mod = os.path.join(workspace_dir, "go.mod")
    cargo_toml = os.path.join(workspace_dir, "Cargo.toml")
    index_html = os.path.join(workspace_dir, "index.html")

    # 1. PHP / Laravel (Checked first because Laravel projects frequently have package.json for Vite/Tailwind)
    if os.path.exists(artisan_file) or os.path.exists(composer_json):
        is_laravel = os.path.exists(artisan_file)
        if not is_laravel and os.path.exists(composer_json):
            try:
                with open(composer_json, "r", encoding="utf-8", errors="ignore") as f:
                    content = f.read().lower()
                    if "laravel" in content:
                        is_laravel = True
            except Exception:
                pass
        return {
            "template_key": "laravel",
            "framework": "Laravel" if is_laravel else "PHP",
            "detected_stack": "PHP / Laravel" if is_laravel else "PHP Generic",
            "recommended_port": 8080,
            "has_standalone": False,
            "package_manager": "composer",
        }

    # 2. JavaScript / TypeScript Node.js ecosystem
    if os.path.exists(pkg_json_file):
        pkg_data: Dict[str, Any] = {}
        try:
            with open(pkg_json_file, "r", encoding="utf-8", errors="ignore") as f:
                pkg_data = json.load(f)
        except Exception:
            pass

        deps = {**pkg_data.get("dependencies", {}), **pkg_data.get("devDependencies", {})}
        deps_keys = {k.lower() for k in deps.keys()}
        scripts = pkg_data.get("scripts", {})

        # Check package manager
        pkg_manager = "npm"
        if os.path.exists(os.path.join(workspace_dir, "pnpm-lock.yaml")):
            pkg_manager = "pnpm"
        elif os.path.exists(os.path.join(workspace_dir, "yarn.lock")):
            pkg_manager = "yarn"
        elif os.path.exists(os.path.join(workspace_dir, "bun.lockb")):
            pkg_manager = "bun"

        # Check Next.js
        if "next" in deps_keys or os.path.exists(os.path.join(workspace_dir, "next.config.js")) or os.path.exists(os.path.join(workspace_dir, "next.config.ts")) or os.path.exists(os.path.join(workspace_dir, "next.config.mjs")):
            return {
                "template_key": "nextjs",
                "framework": "Next.js",
                "detected_stack": "Next.js (App Router / Pages)",
                "recommended_port": 3000,
                "has_standalone": True,
                "package_manager": pkg_manager,
            }

        # Check Vite / SPA / React / Vue / Svelte / Astro
        spa_indicators = {"vite", "react-scripts", "@vue/cli-service", "vue", "@sveltejs/kit", "astro", "nuxt"}
        if any(ind in deps_keys for ind in spa_indicators):
            # Nuxt or SvelteKit SSR might have node backend, but Vite SPAs are static
            if "nuxt" not in deps_keys and "vite" in deps_keys:
                return {
                    "template_key": "vite_spa",
                    "framework": "React / Vite / Vue",
                    "detected_stack": "Vite Single Page Application",
                    "recommended_port": 80,
                    "has_standalone": False,
                    "package_manager": pkg_manager,
                }

        # Check Backend (Express, Nest, Fastify, etc.)
        backend_indicators = {"express", "@nestjs/core", "fastify", "koa", "@adonisjs/core"}
        if any(ind in deps_keys for ind in backend_indicators) or "start" in scripts:
            fw = "NestJS" if "@nestjs/core" in deps_keys else ("Express" if "express" in deps_keys else "Node.js")
            return {
                "template_key": "node_backend",
                "framework": fw,
                "detected_stack": f"{fw} Backend Service",
                "recommended_port": 3000,
                "has_standalone": False,
                "package_manager": pkg_manager,
            }

        return {
            "template_key": "node_backend",
            "framework": "Node.js",
            "detected_stack": "Node.js Application",
            "recommended_port": 3000,
            "has_standalone": False,
            "package_manager": pkg_manager,
        }

    # 3. Python Ecosystem
    py_files = [f for f in ("main.py", "app.py", "manage.py") if os.path.exists(os.path.join(workspace_dir, f))]
    if os.path.exists(req_txt) or os.path.exists(pyproject_toml) or os.path.exists(pipfile) or py_files:
        content_scan = ""
        if os.path.exists(req_txt):
            try:
                with open(req_txt, "r", encoding="utf-8", errors="ignore") as f:
                    content_scan += f.read().lower()
            except Exception:
                pass
        for pf in py_files:
            try:
                with open(os.path.join(workspace_dir, pf), "r", encoding="utf-8", errors="ignore") as f:
                    content_scan += f.read().lower()[:1000]
            except Exception:
                pass

        if "django" in content_scan or os.path.exists(os.path.join(workspace_dir, "manage.py")):
            return {
                "template_key": "django",
                "framework": "Django / Python",
                "detected_stack": "Python Django Framework",
                "recommended_port": 8000,
                "has_standalone": False,
                "package_manager": "pip",
            }
        elif "fastapi" in content_scan or "uvicorn" in content_scan:
            return {
                "template_key": "fastapi",
                "framework": "FastAPI",
                "detected_stack": "Python FastAPI / Uvicorn",
                "recommended_port": 8000,
                "has_standalone": False,
                "package_manager": "pip",
            }
        elif "flask" in content_scan:
            return {
                "template_key": "flask",
                "framework": "Flask",
                "detected_stack": "Python Flask Framework",
                "recommended_port": 5000,
                "has_standalone": False,
                "package_manager": "pip",
            }
        else:
            return {
                "template_key": "fastapi",
                "framework": "Python",
                "detected_stack": "Python Service",
                "recommended_port": 8000,
                "has_standalone": False,
                "package_manager": "pip",
            }

    # 4. Go
    if os.path.exists(go_mod):
        return {
            "template_key": "golang",
            "framework": "Go",
            "detected_stack": "Go Microservice",
            "recommended_port": 8080,
            "has_standalone": True,
            "package_manager": "go",
        }

    # 5. Static HTML
    if os.path.exists(index_html):
        return {
            "template_key": "static_html",
            "framework": "Static HTML",
            "detected_stack": "Static Web (Nginx)",
            "recommended_port": 80,
            "has_standalone": False,
            "package_manager": "none",
        }

    # Default fallback
    return {
        "template_key": "nextjs",
        "framework": "Generic Web App",
        "detected_stack": "Generic Web Container",
        "recommended_port": 3000,
        "has_standalone": False,
        "package_manager": "auto",
    }


def generate_dockerfile(
    template_key: str,
    port: int = 3000,
    project_name: Optional[str] = None
) -> str:
    """Generate a production-ready, multi-stage Dockerfile tailored to the specified framework template."""
    tmpl = TEMPLATES.get(template_key)
    if not tmpl:
        # Fallback to nextjs or generic
        tmpl = TEMPLATES["nextjs"]

    raw = tmpl["content"]
    # Replace default port with configured target port if different
    default_p = str(tmpl.get("default_port", 3000))
    target_p = str(port)
    if default_p != target_p:
        raw = raw.replace(f"EXPOSE {default_p}", f"EXPOSE {target_p}")
        raw = raw.replace(f"PORT={default_p}", f"PORT={target_p}")

    return raw


def generate_dockerignore() -> str:
    """Returns the standardized, high-performance .dockerignore configuration."""
    return DOCKERIGNORE_DEFAULT


def ensure_dockerfile_and_ignore(
    workspace_dir: str,
    dockerfile_path: str = "Dockerfile",
    fallback_framework: str = "auto",
    container_port: int = 3000,
    log_callback: Optional[Callable[[str, str], None]] = None
) -> Tuple[str, bool, bool]:
    """
    Ensures that a project workspace has:
    1. An optimized Dockerfile (auto-detecting and generating multi-stage build if missing).
    2. A professional .dockerignore preventing context upload bloat.

    Returns:
        (resolved_dockerfile_relative_path, dockerfile_was_created, dockerignore_was_created)
    """
    def log(level: str, msg: str):
        if log_callback:
            log_callback(level, msg)

    df_created = False
    di_created = False

    target_df = os.path.join(workspace_dir, dockerfile_path or "Dockerfile")
    dockerignore_path = os.path.join(workspace_dir, ".dockerignore")

    # 1. Check or generate .dockerignore first to protect build context
    if not os.path.exists(dockerignore_path):
        try:
            with open(dockerignore_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(generate_dockerignore())
            di_created = True
            log("info", "[PSM Deployer] 🛡️ Otomatis menambahkan file '.dockerignore' optimal untuk mencegah bloat context Docker.")
        except Exception as e:
            log("warning", f"[PSM Deployer] Gagal membuat .dockerignore: {e}")

    # 2. Check if Dockerfile exists
    if os.path.exists(target_df):
        return dockerfile_path, False, di_created

    # Also check if root Dockerfile exists
    root_df = os.path.join(workspace_dir, "Dockerfile")
    if os.path.exists(root_df):
        return "Dockerfile", False, di_created

    # 3. Detect stack and generate Dockerfile
    detection = detect_project_stack(workspace_dir)
    tmpl_key = detection["template_key"]

    # Match fallback_framework if explicitly chosen by user
    if fallback_framework and fallback_framework.lower() != "auto":
        fw_clean = fallback_framework.lower()
        if "next" in fw_clean:
            tmpl_key = "nextjs"
        elif "vite" in fw_clean or "react" in fw_clean or "vue" in fw_clean:
            tmpl_key = "vite_spa"
        elif "node" in fw_clean or "express" in fw_clean or "nest" in fw_clean:
            tmpl_key = "node_backend"
        elif "fastapi" in fw_clean:
            tmpl_key = "fastapi"
        elif "django" in fw_clean:
            tmpl_key = "django"
        elif "flask" in fw_clean:
            tmpl_key = "flask"
        elif "laravel" in fw_clean or "php" in fw_clean:
            tmpl_key = "laravel"
        elif "go" in fw_clean:
            tmpl_key = "golang"
        elif "static" in fw_clean or "html" in fw_clean:
            tmpl_key = "static_html"

    eff_port = container_port or detection.get("recommended_port", 3000)
    content = generate_dockerfile(tmpl_key, port=eff_port)

    # Write Dockerfile to workspace root
    out_rel = dockerfile_path if dockerfile_path and dockerfile_path != "." else "Dockerfile"
    out_abs = os.path.join(workspace_dir, out_rel)
    os.makedirs(os.path.dirname(out_abs), exist_ok=True)

    with open(out_abs, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    df_created = True

    stack_name = TEMPLATES.get(tmpl_key, {}).get("name", detection.get("detected_stack", "Web Application"))
    log("info", f"[PSM Deployer] 🐳 Professional Dockerfile Setup Assistant aktif!")
    log("info", f"[PSM Deployer] 📝 Otomatis menambahkan 'Dockerfile' multi-stage production untuk stack: {stack_name} (Port: {eff_port}).")

    return out_rel, df_created, di_created


